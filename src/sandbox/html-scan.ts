import type { HtmlFinding } from '../shared/protocol.ts'

/**
 * Reads an HTML attachment for what it could do, so the preview only warns when
 * there is something to warn about.
 *
 * This is a signal for the reader, **not a security boundary**. Whether a script
 * is harmful cannot be decided by reading it, and a fake form drawn as a picture
 * has no markup to find. The CSP and the sandbox flags hold whatever this misses,
 * which is why nothing may be relaxed on the strength of a clean result, and why
 * the wording built from it never calls a file safe.
 *
 * It reads the document that is about to render, after asset inlining, so an
 * inlined CDN script is read too. It parses with `DOMParser` because the answer
 * has to agree with the browser's parser, and unlike `inline-assets.ts` it never
 * writes anything back, so the round-trip objection does not apply. `DOMParser`
 * runs nothing and loads nothing.
 */

/** Runs the decoded result, or writes it into the page. */
const DECODE_AND_RUN =
  /(?:\beval|\bFunction|\bdocument\.write(?:ln)?)\s*\(\s*(?:window\.|self\.|globalThis\.)?(?:atob|unescape|decodeURI(?:Component)?|String\.fromCharCode)\b/

/** The output of Dean Edwards' packer, which still circulates. */
const PACKER = /\beval\s*\(\s*function\s*\(\s*p\s*,\s*a\s*,\s*c\s*,\s*k\b/

/** A character-code list long enough to be hiding text rather than building a symbol. */
const CHAR_CODE_LIST = /fromCharCode\s*\(\s*(?:\d+\s*,\s*){20,}/

/** `\x` runs. `\u` is left out: minifiers emit it for ordinary non-Latin text. */
const HEX_ESCAPE_RUN = /(?:\\x[0-9a-fA-F]{2}){20,}/

/** Identifiers as generated by javascript-obfuscator. */
const OBFUSCATOR_NAME = /\b_0x[0-9a-f]{4,}\b/g
const OBFUSCATOR_NAME_MIN = 5

const LONG_ENCODED = /(?<!base64,)(?<![A-Za-z0-9+/])[A-Za-z0-9+/]{2000,}/
const DECODER = /\b(?:atob|unescape|fromCharCode|eval)\b/

/**
 * Whether code looks deliberately disguised.
 *
 * A bare `eval`, `atob` or `fromCharCode` does not count. Ordinary minified
 * libraries use all three, and a red banner on every chart library would teach
 * people to ignore it. `html-scan.test.ts` pins this against the libraries in
 * `node_modules`. What counts is the shape: decoding and then running the result.
 */
export function looksObfuscated(code: string): boolean {
  if (DECODE_AND_RUN.test(code) || PACKER.test(code)) return true
  if (CHAR_CODE_LIST.test(code) || HEX_ESCAPE_RUN.test(code)) return true
  if ((code.match(OBFUSCATOR_NAME)?.length ?? 0) >= OBFUSCATOR_NAME_MIN) return true
  return LONG_ENCODED.test(code) && DECODER.test(code)
}

/**
 * Words a sign-in page uses. Vietnamese and Japanese are here because that is who
 * reads these previews. It only ever applies to controls and headings, since prose
 * about passwords is common in the documents people actually send.
 */
const LOGIN_WORDS =
  /\b(?:sign[\s-]?in|log[\s-]?[io]n|password|passcode|verify your (?:account|identity))\b|mật khẩu|đăng nhập|パスワード|ログイン|サインイン|暗証番号/i

export function hasLoginWording(text: string): boolean {
  return LOGIN_WORDS.test(text)
}

/** What the document holds. Separate from the DOM walk so the policy tests in Node. */
export interface HtmlFacts {
  scripts: boolean
  /** Script bodies, event handlers and `javascript:` URLs. */
  code: string[]
  redirects: boolean
  passwordField: boolean
  textInput: boolean
  loginButton: boolean
  /** Sign-in wording in a heading, title, label or placeholder. */
  loginHeading: boolean
  embedded: boolean
  remote: boolean
}

export function findingsFromFacts(facts: HtmlFacts): HtmlFinding[] {
  const findings: HtmlFinding[] = []

  if (facts.code.some(looksObfuscated)) findings.push('obfuscated')
  if (facts.redirects) findings.push('redirect')
  if (facts.passwordField) findings.push('password')
  // A heading alone is a design document about a login flow. It takes a field to
  // type into, or a button claiming to sign in, before it reads as a sign-in page.
  else if (facts.loginButton || (facts.loginHeading && facts.textInput)) findings.push('login')
  if (facts.embedded) findings.push('embedded')
  if (facts.scripts) findings.push('scripts')
  if (facts.textInput && !facts.passwordField) findings.push('inputs')
  if (facts.remote) findings.push('remote')

  return findings
}

const NON_TEXT_INPUTS = new Set([
  'hidden',
  'checkbox',
  'radio',
  'button',
  'submit',
  'reset',
  'image',
  'range',
  'color',
  'file',
])
const SUBMIT_INPUTS = new Set(['button', 'submit'])
const EMBEDS = new Set(['iframe', 'frame', 'object', 'embed'])
const HEADINGS = new Set(['h1', 'h2', 'h3', 'title', 'label', 'legend'])
const MEDIA = new Set(['img', 'audio', 'video', 'source', 'track', 'image'])

const REMOTE_URL = /^\s*(?:https?:)?\/\//i
const REMOTE_IN_CSS = /(?:url\(\s*|@import\s+)['"]?\s*(?:https?:)?\/\//i
const PASSWORD_HINT = /(?<![a-z])(?:pass(?:word|code|wd)?|pwd)(?![a-z])|mật khẩu|パスワード/i
const JS_MIME = /^(?:|module|.*(?:java|ecma|j|live)script.*)$/i

function isJavaScriptUrl(value: string): boolean {
  // Whitespace and control characters are stripped by browsers, so `java\tscript:`
  // is a scheme to them. Same reasoning as the Markdown link filter.
  return /^javascript:/i.test(value.replace(/[\u0000- ]/g, ''))
}

export function collectFacts(document: Document): HtmlFacts {
  const facts: HtmlFacts = {
    scripts: false,
    code: [],
    redirects: false,
    passwordField: false,
    textInput: false,
    loginButton: false,
    loginHeading: false,
    embedded: false,
    remote: false,
  }

  // `querySelectorAll` does not enter a <template>, and `DOMParser` leaves a
  // declarative shadow root as one. An iframe would show its contents, so a
  // password field inside `<template shadowrootmode>` has to be walked here.
  const roots: ParentNode[] = [document]

  for (const root of roots) {
    for (const element of root.querySelectorAll('*')) {
      const name = element.localName

      if (name === 'template') roots.push((element as HTMLTemplateElement).content)
      if (EMBEDS.has(name)) facts.embedded = true
      if (HEADINGS.has(name) && hasLoginWording(element.textContent ?? '')) {
        facts.loginHeading = true
      }

      for (const attribute of element.attributes) {
        const attr = attribute.name.toLowerCase()
        if (attr.startsWith('on')) {
          facts.scripts = true
          facts.code.push(attribute.value)
        } else if (isJavaScriptUrl(attribute.value)) {
          facts.scripts = true
          facts.code.push(attribute.value)
        } else if (attr === 'style') {
          readCss(attribute.value, facts)
        } else if (attr === 'placeholder' && hasLoginWording(attribute.value)) {
          facts.loginHeading = true
        } else if (attr === 'contenteditable' && attribute.value.toLowerCase() !== 'false') {
          facts.textInput = true
        }
      }

      if (name === 'script') {
        const type = element.getAttribute('type')?.trim() ?? ''
        // A `<script type="application/json">` is data and never runs.
        if (JS_MIME.test(type)) {
          facts.scripts = true
          facts.code.push(element.textContent ?? '')
          if (REMOTE_URL.test(element.getAttribute('src') ?? '')) facts.remote = true
        }
      } else if (name === 'style') {
        readCss(element.textContent ?? '', facts)
      } else if (name === 'meta') {
        const equiv = element.getAttribute('http-equiv')?.trim().toLowerCase()
        // A refresh with no URL only reloads the same document.
        if (equiv === 'refresh' && /url\s*=/i.test(element.getAttribute('content') ?? '')) {
          facts.redirects = true
        }
      } else if (name === 'link') {
        const rel = element.getAttribute('rel')?.toLowerCase() ?? ''
        if (rel.includes('stylesheet') && REMOTE_URL.test(element.getAttribute('href') ?? '')) {
          facts.remote = true
        }
      } else if (name === 'input') {
        readInput(element, facts)
      } else if (name === 'textarea') {
        facts.textInput = true
      } else if (name === 'button' || element.getAttribute('role') === 'button') {
        if (hasLoginWording(element.textContent ?? '')) facts.loginButton = true
      }

      if (MEDIA.has(name)) {
        const url = element.getAttribute('src') ?? element.getAttribute('href') ?? ''
        if (REMOTE_URL.test(url)) facts.remote = true
      }
    }
  }

  return facts
}

function readInput(input: Element, facts: HtmlFacts): void {
  const type = input.getAttribute('type')?.trim().toLowerCase() ?? 'text'

  if (SUBMIT_INPUTS.has(type) && hasLoginWording(input.getAttribute('value') ?? '')) {
    facts.loginButton = true
  }
  if (NON_TEXT_INPUTS.has(type)) return

  facts.textInput = true

  const hints = ['name', 'id', 'placeholder', 'autocomplete', 'aria-label']
    .map((attribute) => input.getAttribute(attribute) ?? '')
    .join(' ')
  if (type === 'password' || PASSWORD_HINT.test(hints)) facts.passwordField = true
}

function readCss(css: string, facts: HtmlFacts): void {
  // Masks a plain text input as dots, which is a password field in everything but name.
  if (css.includes('-webkit-text-security')) facts.passwordField = true
  if (REMOTE_IN_CSS.test(css)) facts.remote = true
}

/** Never throws: a file that cannot be read is reported, not waved through. */
export function scanHtml(html: string): HtmlFinding[] {
  try {
    return findingsFromFacts(collectFacts(new DOMParser().parseFromString(html, 'text/html')))
  } catch {
    return ['unchecked']
  }
}
